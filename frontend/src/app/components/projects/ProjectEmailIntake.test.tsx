import { beforeEach, expect, it, vi } from "vitest";
import { fireEvent, render, screen, waitFor } from "@testing-library/react";
const api = vi.hoisted(() => ({ previewProjectEmail: vi.fn(), importProjectEmail: vi.fn(), latestProjectEmail: vi.fn(), getProjectEmailReceipt: vi.fn(), getDocumentFileUrl: vi.fn() }));
vi.mock("@/app/lib/mikeApi", () => api);
vi.mock("@/app/lib/userFacingError", () => ({ notifyError: vi.fn() }));
import { ProjectEmailIntake } from "./ProjectEmailIntake";
const preview = { id: "preview", accountEmail: "long-fixture-address@example.invalid", query: "subject:synthetic", messages: [{ id: "m1", subject: "First update", from: "fixture@example.invalid", date: "2 November 2026", excerpt: "<script>do not execute me</script>", attachments: [{ name: "contract.pdf", size: 20 }] }, { id: "m2", subject: "Second update", from: "other@example.invalid", date: "", excerpt: "Other matter", attachments: [] }] };
const receipt = { previewId: "preview", query: "subject:synthetic", messages: [{ id: "m1", subject: "First update", complete: true, items: [{ name: "Email-m1.docx", status: "imported", documentId: "doc", versionId: "v1" }] }] };
const mount = () => render(<ProjectEmailIntake projectId="project" folderId={null} projectName="Fictional matter" onClose={vi.fn()} onImported={async () => {}} />);
beforeEach(() => { vi.resetAllMocks(); api.latestProjectEmail.mockResolvedValue(null); api.previewProjectEmail.mockResolvedValue(preview); api.importProjectEmail.mockResolvedValue(receipt); api.getDocumentFileUrl.mockReturnValue("/safe-source-version"); });
it("requires explicit message selection and project-sharing confirmation before import", async () => {
  const { container } = mount();
  await waitFor(() => expect(screen.getByLabelText("Gmail query")).toBeEnabled());
  fireEvent.change(screen.getByLabelText("Gmail query"), { target: { value: "subject:synthetic" } });
  fireEvent.click(screen.getByRole("button", { name: "Preview messages" }));
  await screen.findByText("First update");
  expect(screen.getByRole("button", { name: "Import selected" })).toBeDisabled();
  expect(api.importProjectEmail).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole("checkbox", { name: /First update/ }));
  expect(screen.getByRole("button", { name: "Import selected" })).toBeDisabled();
  fireEvent.click(screen.getByRole("checkbox", { name: /Share the selected messages/ }));
  fireEvent.click(screen.getByRole("button", { name: "Import selected" }));
  await waitFor(() => expect(api.importProjectEmail).toHaveBeenCalledWith("project", "preview", ["m1"]));
  expect(container.querySelector("script")).toBeNull();
  await screen.findByRole("link", { name: "Email-m1.docx" });
  expect(api.getDocumentFileUrl).toHaveBeenCalledWith("doc", "v1");
});
it("restores a durable incomplete confirmation and offers the same-ID retry after reload", async () => {
  api.latestProjectEmail.mockResolvedValue({ id: "preview", query: "subject:synthetic", confirmed_at: "2026-11-02" });
  api.getProjectEmailReceipt.mockResolvedValue({ ...receipt, messages: [{ ...receipt.messages[0], complete: false, items: [{ name: "Email-m1.docx", status: "failed" }] }] });
  mount();
  const retry = await screen.findByRole("button", { name: "Retry confirmed selection" });
  await waitFor(() => expect(retry).toBeEnabled());
  fireEvent.click(retry);
  await waitFor(() => expect(api.importProjectEmail).toHaveBeenCalledWith("project", "preview", ["m1"]));
  expect(api.previewProjectEmail).not.toHaveBeenCalled();
});
it("editing the query clears a prior confirmation instead of silently retargeting it", async () => {
  api.latestProjectEmail.mockResolvedValue({ id: "preview", query: "subject:synthetic", confirmed_at: "2026-11-02" });
  api.getProjectEmailReceipt.mockResolvedValue(receipt);
  mount();
  await screen.findByRole("heading", { name: /What changed/ });
  await waitFor(() => expect(screen.getByLabelText("Gmail query")).toBeEnabled());
  fireEvent.change(screen.getByLabelText("Gmail query"), { target: { value: "different query" } });
  expect(screen.queryByRole("button", { name: "Retry confirmed selection" })).not.toBeInTheDocument();
  expect(api.importProjectEmail).not.toHaveBeenCalled();
});
it("does not offer ineffective retries for excluded, deleted, changed or unverifiable imports", async () => {
  api.latestProjectEmail.mockResolvedValue({ id: "preview", query: "subject:synthetic", confirmed_at: "2026-11-02" });
  api.getProjectEmailReceipt.mockResolvedValue({ ...receipt, messages: [{ ...receipt.messages[0], complete: false, items: [{ name: "mail.eml", status: "excluded" }, { name: "old.pdf", status: "deleted" }, { name: "edited.docx", status: "source_changed", documentId: "stale-doc", versionId: "stale-version", detail: "The imported source version was edited or replaced." }, { name: "unknown.docx", status: "source_unverified", documentId: "unverified-doc", versionId: "unverified-version", detail: "The original imported source cannot be verified." }] }] });
  mount();
  await screen.findByText(/Retrying the restored confirmation keeps its original destination/);
  await waitFor(() => expect(screen.getByRole("button", { name: "Retry confirmed selection" })).toBeDisabled());
  expect(screen.queryByRole("link")).not.toBeInTheDocument();
  expect(api.getDocumentFileUrl).not.toHaveBeenCalled();
  expect(screen.getByText(/edited.docx: source changed/)).toBeInTheDocument();
  expect(screen.getByText(/unknown.docx: source unverified/)).toBeInTheDocument();
  expect(api.importProjectEmail).not.toHaveBeenCalled();
});
it("offers retry for genuine mixed failures while changed sources remain incomplete and unlinked", async () => {
  api.latestProjectEmail.mockResolvedValue({ id: "preview", query: "subject:synthetic", confirmed_at: "2026-11-02" });
  api.getProjectEmailReceipt.mockResolvedValue({ ...receipt, messages: [{ ...receipt.messages[0], complete: false, items: [{ name: "Email-m1.docx", status: "source_changed" }, { name: "contract.pdf", status: "failed" }] }] });
  mount();
  const retry = await screen.findByRole("button", { name: "Retry confirmed selection" });
  await waitFor(() => expect(retry).toBeEnabled());
  expect(screen.queryByRole("link")).not.toBeInTheDocument();
  fireEvent.click(retry);
  await waitFor(() => expect(api.importProjectEmail).toHaveBeenCalledWith("project", "preview", ["m1"]));
});
it("labels a repeated preview as loading without implying an unconfirmed import", async () => {
  let finishPreview!: (value: typeof preview) => void;
  api.previewProjectEmail.mockResolvedValueOnce(preview).mockImplementationOnce(() => new Promise(resolve => { finishPreview = resolve; }));
  mount();
  await waitFor(() => expect(screen.getByLabelText("Gmail query")).toBeEnabled());
  fireEvent.change(screen.getByLabelText("Gmail query"), { target: { value: "subject:synthetic" } });
  fireEvent.click(screen.getByRole("button", { name: "Preview messages" }));
  await screen.findByRole("button", { name: "Import selected" });
  fireEvent.click(screen.getByRole("button", { name: "Preview messages" }));
  expect(await screen.findByText("Reading a bounded Gmail page…")).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "Loading…" })).toBeDisabled();
  expect(screen.queryByText(/Importing selected sources/)).not.toBeInTheDocument();
  expect(api.importProjectEmail).not.toHaveBeenCalled();
  finishPreview(preview);
  await screen.findByRole("button", { name: "Import selected" });
});
